FROM KHACHHANG KH
JOIN HOADON HD ON KH.MAKH=HD.MAKH
WHERE HD.NGHD='2007-01-01';
--CAU 9
SELECT HD.SOHD, HD.TRIGIA
FROM HOADON HD JOIN NHANVIEN NV ON HD.MANV=NV.MANV
WHERE NV.HOTEN = N'Nguyen Van B' AND HD.NGHD = '2006-10-28';
--CAU 10
SELECT DISTINCT SP.MASP, SP.TENSP
FROM SANPHAM SP
JOIN CTHD CT ON SP.MASP = CT.MASP
JOIN HOADON HD ON CT.SOHD = HD.SOHD
JOIN KHACHHANG KH ON HD.MAKH = KH.MAKH
WHERE KH.HOTEN = N'Nguyen Van A' AND MONTH(HD.NGHD) = 10 AND YEAR(HD.NGHD) = 2006;
--CAU 11
